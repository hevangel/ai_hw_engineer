#!/usr/bin/env python3
"""Fetch official tool references with Firecrawl CLI, preserving project guides."""

import argparse
from datetime import datetime, timezone
import difflib
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
from urllib.parse import urlparse


ROOT = Path(__file__).resolve().parent.parent
MANIFEST = Path(__file__).with_name("tool_doc_sources.json")


def safe_name(name):
    return isinstance(name, str) and re.fullmatch(r"[a-z0-9][a-z0-9_-]*", name)


def source_url(url):
    parsed = urlparse(url)
    if parsed.scheme != "https" or not parsed.hostname or parsed.username or parsed.password:
        raise ValueError(f"Expected a public HTTPS source URL: {url}")
    return url


def load_sources():
    sources = json.loads(MANIFEST.read_text(encoding="utf-8"))
    for tool, config in sources.items():
        if not safe_name(tool) or not (ROOT / "docs" / tool).is_dir():
            raise ValueError(f"Unknown documentation folder: {tool}")
        source_url(config["license"])
        if not config["pages"]:
            raise ValueError(f"No pages configured for {tool}")
        for page, url in config["pages"].items():
            if not safe_name(page) or page == "README":
                raise ValueError(f"Invalid page name: {page}")
            source_url(url)
            source_url(config.get("page_licenses", {}).get(page, config["license"]))
    return sources


def destination(relative):
    path = ROOT / relative
    # Resolve symlinks before allowing writes to generated-reference locations.
    if not path.resolve().is_relative_to((ROOT / "docs").resolve()):
        raise ValueError(f"Documentation destination escapes docs/: {relative}")
    if path.is_symlink() or any(parent.is_symlink() for parent in path.parents if parent != ROOT):
        raise ValueError(f"Refusing a symlink destination: {relative}")
    return path


def scrape(url, executable):
    command = [executable, "scrape", url, "--format", "markdown", "--json",
               "--only-main-content", "--max-age", "0"]
    result = subprocess.run(command, capture_output=True, text=True, encoding="utf-8", timeout=180)
    if result.returncode:
        # Do not echo CLI output, which may contain service configuration details.
        raise ValueError(f"Firecrawl failed for {url} (exit {result.returncode}); check CLI auth, network and CA setup")
    response = json.loads(result.stdout)
    if response.get("success") is False:
        raise ValueError(f"Firecrawl reported failure for {url}")
    data = response.get("data", response)
    metadata = data.get("metadata", {})
    status = metadata.get("statusCode")
    if metadata.get("error") or status is None or not 200 <= int(status) < 300:
        raise ValueError(f"Upstream page failed for {url} (status {status})")
    markdown = data.get("markdown")
    if not isinstance(markdown, str) or len(markdown.strip()) < 100:
        raise ValueError(f"Empty or incomplete Markdown from {url}")
    # Reject common bot challenges that otherwise return HTTP 200.
    title = str(metadata.get("title", "")).lower()
    if any(marker in title for marker in ("just a moment", "access denied", "page not found")):
        raise ValueError(f"Upstream returned a challenge or error page for {url}")
    return markdown.replace("\r\n", "\n").strip() + "\n"


def reference(tool, page, url, license_url, markdown, previous):
    content_hash = hashlib.sha256(markdown.encode()).hexdigest()
    header = (f"<!-- Generated by scripts/update_tool_docs.sh; edit the source manifest instead. -->\n"
              f"# {tool}: {page} (upstream reference)\n\n"
              f"Source: <{url}>\n\nUpstream licensing: <{license_url}>\n\n")
    # Preserve the retrieval date for byte-identical content and provenance.
    marker = f"\nContent SHA-256: `{content_hash}`\n\n---\n\n{markdown}"
    if previous.startswith(header) and previous.endswith(marker):
        return previous
    date = datetime.now(timezone.utc).isoformat(timespec="seconds")
    return header + f"Retrieved (UTC): {date}\n" + marker


def main(argv=None):
    sources = load_sources()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tool", action="append", choices=sorted(sources), help="refresh only this tool; repeatable")
    parser.add_argument("--page", action="append", help="refresh only this page slug; repeatable")
    parser.add_argument("--list", action="store_true", help="list configured sources without fetching")
    parser.add_argument("--dry-run", action="store_true", help="fetch and show diff without writing")
    parser.add_argument("--firecrawl-bin", default="firecrawl", help="Firecrawl CLI executable or wrapper")
    args = parser.parse_args(argv)
    selected = [(tool, page, url) for tool, config in sources.items()
                if not args.tool or tool in args.tool
                for page, url in config["pages"].items() if not args.page or page in args.page]
    if not selected or (args.page and set(args.page) - {page for _, page, _ in selected}):
        parser.error("No source configured for the requested tool/page selection")
    if args.list:
        for tool, page, url in selected:
            print(f"{tool}/{page}: {url}")
        return
    if not args.dry_run:
        branch = subprocess.check_output(["git", "branch", "--show-current"], cwd=ROOT, text=True).strip()
        if branch in {"", "main", "master"}:
            raise ValueError("Switch to a feature branch before updating documentation")
    executable = shutil.which(args.firecrawl_bin)
    if not executable:
        raise ValueError("Firecrawl CLI is required; install firecrawl-cli and run firecrawl login")
    original, updated = {}, {}
    for tool, page, url in selected:
        relative = f"docs/{tool}/upstream/{page}.md"
        path = destination(relative)
        original[relative] = path.read_text(encoding="utf-8") if path.exists() else None
        print(f"Fetching {tool}/{page}: {url}", file=sys.stderr)
        markdown = scrape(url, executable)
        config = sources[tool]
        license_url = config.get("page_licenses", {}).get(page, config["license"])
        updated[relative] = reference(tool, page, url, license_url, markdown, original[relative] or "")
    index = "docs/upstream-index.md"
    path = destination(index)
    original[index] = path.read_text(encoding="utf-8") if path.exists() else None
    links = []
    for tool, config in sources.items():
        for page in config["pages"]:
            relative = f"docs/{tool}/upstream/{page}.md"
            if relative in updated or destination(relative).is_file():
                links.append(f"- [{tool}: {page}]({tool}/upstream/{page}.md)")
    updated[index] = ("<!-- Generated by scripts/update_tool_docs.sh. -->\n"
                      "# Upstream tool references\n\n"
                      "These copies describe live upstream documentation and may differ from\n"
                      "the pinned Docker tools. Keep project-specific guides alongside them;\n"
                      "check installed versions before adopting new commands or features.\n\n"
                      + "\n".join(links) + "\n")
    # Finish fetching and validating the whole selection before writing any files.
    for relative, content in updated.items():
        sys.stdout.writelines(difflib.unified_diff((original[relative] or "").splitlines(True),
                                                 content.splitlines(True),
                                                 fromfile="a/" + relative, tofile="b/" + relative))
    if args.dry_run:
        return
    for relative, content in original.items():
        path = destination(relative)
        if (path.read_text(encoding="utf-8") if path.exists() else None) != content:
            raise ValueError(f"{relative} changed during retrieval; retry without concurrent edits")
    for relative, content in updated.items():
        if original[relative] != content:
            path = destination(relative)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    print(f"Refreshed {len(selected)} upstream references; project guides preserved.", file=sys.stderr)


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, subprocess.SubprocessError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        sys.exit(1)

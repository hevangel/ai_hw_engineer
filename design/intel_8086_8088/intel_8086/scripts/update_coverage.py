#!/usr/bin/env python3
"""Produce an explicit encoding ledger from immutable external metadata."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
selection = json.loads((ROOT / 'work/vector_selection.json').read_text())
metadata = json.loads((ROOT / 'work/reference/v1/metadata.json').read_text())['opcodes']
directed = {0x9b: 'WAIT busy/ready/interrupt restart (control + native)',
            0xf4: 'HLT idle/wakeup (control + native + UVM + formal)',
            0xf0: 'LOCK/HOLD atomicity (control + native)',
            0xf2: 'REPNE physical string fixtures', 0xf3: 'REP/REPE physical fixtures and interrupted restart'}
directed.update({op: 'ESC: all eight groups, register and odd-word memory (control)'
                 for op in range(0xd8, 0xe0)})
directed.update({op: 'Segment override: physical fixtures and directed boundary tests'
                 for op in (0x26, 0x2e, 0x36, 0x3e)})
rows = []
gaps = []
for op in range(256):
    info = metadata[f'{op:02X}']
    leaves = list(info.get('reg', {}).items()) or [('', {})]
    for group, detail in leaves:
        status = detail.get('status', info.get('status', 'unspecified'))
        stem = f'{op:02X}' + (f'.{group}' if group else '')
        count = selection['files'].get(f'v1/{stem}.json.gz', 0)
        if group == '0' and not count:
            count = selection['files'].get(f'v1/{op:02X}.json.gz', 0)
        evidence = f'{count:,} physical-chip fixtures per interface' if count else directed.get(op, '')
        if op == 0x0f:
            # Metadata says normal, but the manufacturer leaves this encoding
            # undocumented; the upstream README omits it, and die research
            # identifies it explicitly as undocumented POP CS.
            status = 'undocumented (upstream labels normal)'
            evidence = ('Outside documented contract: POP CS; omitted by upstream. '
                        '[Original die analysis](https://www.righto.com/2023/07/undocumented-8086-instructions.html)')
        if status in ('normal', 'fpu') and not evidence:
            gaps.append(stem)
        if not evidence:
            evidence = 'Outside documented contract; excluded with upstream status'
        if op == 0x82:
            evidence = 'Original DEBUG.COM exercises this 80h alias; alias corpus excluded explicitly'
        rows.append(f'| {stem} | {status} | {evidence} |')
if gaps:
    raise ValueError('Documented encoding coverage gaps: ' + ', '.join(gaps))
text = '''# Encoding coverage ledger

Generated by `scripts/update_coverage.py` from the pinned external metadata and
fixture-selection counts. This is an encoding/evidence ledger, not a claim of
exhaustive state-space or original-silicon cycle coverage. See the specification
for the documented instruction families and the verification plan for comparison
rules. Every accepted fixture runs through the EU, native minimum-mode and native
maximum-mode interfaces. FF /2 register CALL, absent from the upstream generator,
has an additional directed exact-target/return test. CL=255 has directed coverage.

| Opcode / ModR/M group | Upstream classification | Verification evidence |
|---|---|---|
'''
(ROOT / 'report/encoding_coverage.md').write_text(text + '\n'.join(rows) + '\n')
(ROOT / 'report/vector_coverage.json').write_text(json.dumps(selection, indent=2) + '\n')
print(f'PASS: documented encoding coverage ledger has no unassigned rows ({len(rows)} total rows)')

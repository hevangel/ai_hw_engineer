`timescale 1ns / 1ps
// Chip-only native digital interface. Pin multiplexing is represented explicitly.
module intel_8086_chip (
    input logic clk,
    reset_i,
    min_mode_i,
    ready_i,
    intr_i,
    nmi_i,
    test_n_i,
    hold_i,
    input logic [1:0] rqgt_n_i,
    input logic [15:0] ad_i,
    output logic [15:0] ad_o,
    output logic ad_oe_o,
    output logic [3:0] address_status_o,
    output logic address_status_oe_o,
    bhe_status_n_o,
    bhe_oe_o,
    output logic rd_n_o,
    wr_n_o,
    m_io_o,
    dt_r_o,
    den_n_o,
    ale_o,
    inta_n_o,
    output logic control_oe_o,
    hlda_o,
    output logic [1:0] rqgt_n_o,
    rqgt_oe_o,
    output logic [2:0] status_o,
    phase_o,
    output logic [1:0] qs_o,
    output logic lock_n_o,
    output logic halted_o,
    fault_o,
    retire_o,
    output logic [127:0] regs_o,
    output logic [63:0] segs_o,
    output logic [15:0] ip_o,
    flags_o,
    output logic [2:0] queue_count_o
);
  logic req, writing, fetching, first, io, intack, core_ready, redirect, locked, suspend_prefetch, inhibit_arbitration;
  logic [19:0] address;
  logic [1:0] be, segment_code;
  logic [15:0] write_data, read_data;
  logic arbitration_pending;
  logic unused_hlda, unused_esc;
  logic [ 5:0] unused_esc_opcode;
  logic [19:0] unused_esc_address;
  intel_8086 eu (
      .clk(clk),
      .rst_n(!reset_i),
      .bus_ready_i(core_ready),
      .bus_rdata_i(read_data),
      .intr_i(intr_i && !arbitration_pending),
      .nmi_i(nmi_i),
      .hold_i(1'b0),
      .test_n_i(test_n_i),
      .bus_req_o(req),
      .bus_write_o(writing),
      .bus_fetch_o(fetching),
      .bus_first_o(first),
      .bus_io_o(io),
      .bus_intack_o(intack),
      .bus_addr_o(address),
      .bus_be_o(be),
      .bus_segment_o(segment_code),
      .bus_wdata_o(write_data),
      .halted_o(halted_o),
      .fault_o(fault_o),
      .retire_o(retire_o),
      .lock_o(locked),
      .hlda_o(unused_hlda),
      .redirect_o(redirect),
      .prefetch_suspend_o(suspend_prefetch),
      .arbitration_inhibit_o(inhibit_arbitration),
      .esc_valid_o(unused_esc),
      .esc_opcode_o(unused_esc_opcode),
      .esc_address_o(unused_esc_address),
      .regs_o(regs_o),
      .segs_o(segs_o),
      .ip_o(ip_o),
      .flags_o(flags_o)
  );
  intel_8086_biu biu (
      .clk(clk),
      .rst_n(!reset_i),
      .min_mode_i(min_mode_i),
      .ready_i(ready_i),
      .ad_i(ad_i),
      .hold_i(hold_i),
      .rqgt_n_i(rqgt_n_i),
      .eu_req_i(req),
      .eu_write_i(writing),
      .eu_fetch_i(fetching),
      .eu_first_i(first),
      .eu_io_i(io),
      .eu_intack_i(intack),
      .eu_addr_i(address),
      .eu_be_i(be),
      .eu_segment_i(segment_code),
      .eu_wdata_i(write_data),
      .flush_i(redirect),
      .suspend_i(suspend_prefetch),
      .inhibit_i(inhibit_arbitration),
      .lock_i(locked),
      .halted_i(halted_o),
      .if_i(flags_o[9]),
      .cs_i(segs_o[31:16]),
      .ip_i(ip_o),
      .eu_ready_o(core_ready),
      .eu_rdata_o(read_data),
      .ad_o(ad_o),
      .ad_oe_o(ad_oe_o),
      .address_status_o(address_status_o),
      .address_status_oe_o(address_status_oe_o),
      .bhe_status_n_o(bhe_status_n_o),
      .bhe_oe_o(bhe_oe_o),
      .rd_n_o(rd_n_o),
      .wr_n_o(wr_n_o),
      .m_io_o(m_io_o),
      .dt_r_o(dt_r_o),
      .den_n_o(den_n_o),
      .ale_o(ale_o),
      .inta_n_o(inta_n_o),
      .control_oe_o(control_oe_o),
      .hlda_o(hlda_o),
      .rqgt_n_o(rqgt_n_o),
      .rqgt_oe_o(rqgt_oe_o),
      .status_o(status_o),
      .phase_o(phase_o),
      .qs_o(qs_o),
      .lock_n_o(lock_n_o),
      .arbitration_pending_o(arbitration_pending),
      .queue_count_o(queue_count_o)
  );
endmodule

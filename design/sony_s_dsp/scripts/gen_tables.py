#!/usr/bin/env python3
"""Generate the S-DSP constant tables as SystemVerilog includes:
  src/sony_s_dsp_gauss.svh  512-entry interpolation kernel, built from the
                            published closed-form construction (ares,
                            gaussianConstructTable). scripts/check_gauss.py
                            compares it with an independent hardware dump.
  src/sony_s_dsp_sched.svh  the 32-phase-per-sample step schedule, expanded
                            into one micro-op per master clock."""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def gauss_table():
    table = [0.0] * 512
    for n in range(512):
        k = 0.5 + n
        s = math.sin(math.pi * k * 1.280 / 1024)
        t = (math.cos(math.pi * k * 2.000 / 1023) - 1) * 0.50
        u = (math.cos(math.pi * k * 4.000 / 1023) - 1) * 0.08
        table[511 - n] = s * (t + u + 1.0) / k
    out = [0] * 512
    for phase in range(128):
        idx = (phase, phase + 256, 511 - phase, 255 - phase)
        scale = 2048.0 / sum(table[i] for i in idx)
        for i in idx:
            out[i] = int(table[i] * scale + 0.5)
    return out


# Steps per phase (sample clock / 32), in execution order.
PHASES = [
    "v5 0;v2 1", "v6 0;v3 1", "v7 0;v4 1;v1 3", "v8 0;v5 1;v2 2",
    "v9 0;v6 1;v3 2", "v7 1;v4 2;v1 4", "v8 1;v5 2;v2 3", "v9 1;v6 2;v3 3",
    "v7 2;v4 3;v1 5", "v8 2;v5 3;v2 4", "v9 2;v6 3;v3 4", "v7 3;v4 4;v1 6",
    "v8 3;v5 4;v2 5", "v9 3;v6 4;v3 5", "v7 4;v4 5;v1 7", "v8 4;v5 5;v2 6",
    "v9 4;v6 5;v3 6", "v1 0;v7 5;v4 6", "v8 5;v5 6;v2 7", "v9 5;v6 6;v3 7",
    "v1 1;v7 6;v4 7", "v8 6;v5 7;v2 0", "v3a 0;v9 6;v6 7;e22", "v7 7;e23",
    "v8 7;e24", "v3b 0;v9 7;e25", "e26", "m27;e27", "m28;e28", "m29;e29",
    "m30;v3c 0;e30", "v4 0;v1 2",
]
EXPAND = {
    "v1": ["V1"], "v2": ["V2A", "V2B", "V2C"],
    "v3": ["V3A", "V3BA", "V3BB", "V3BC", "V3C1", "V3C2"],
    "v3a": ["V3A"], "v3b": ["V3BA", "V3BB", "V3BC"], "v3c": ["V3C1", "V3C2"],
    "v4": ["V4A", "V4B", "V4C", "V4D", "V4E", "V4F"],
    "v5": ["V5"], "v6": ["V6"], "v7": ["V7"], "v8": ["V8"], "v9": ["V9"],
    "e22": ["E22A", "E22B", "E22C"], "e23": ["E23A", "E23B", "E23C"],
    "e24": ["E24"], "e25": ["E25"], "e26": ["E26"], "e27": ["E27"], "e28": ["E28"],
    "e29": ["E29A", "E29B"], "e30": ["E30A", "E30B"],
    "m27": ["M27"], "m28": ["M28"], "m29": ["M29"], "m30": ["M30"],
}
OPS = ["END"] + sorted({u for v in EXPAND.values() for u in v})


def main():
    g = gauss_table()
    lines = ["// Generated by scripts/gen_tables.py; do not edit.",
             "function automatic logic [10:0] gauss(input logic [8:0] i);",
             "    case (i)"]
    lines += [f"        9'd{i}: gauss = 11'd{v};" for i, v in enumerate(g)]
    lines += ["        default: gauss = 11'd0;", "    endcase", "endfunction", ""]
    (ROOT / "src" / "sony_s_dsp_gauss.svh").write_text("\n".join(lines))

    lines = ["// Generated by scripts/gen_tables.py; do not edit.",
             "typedef enum logic [5:0] {"]
    lines.append(",\n".join(f"    U_{o}" for o in OPS))
    lines += ["} uop_t;", "",
              "// {op, voice} for micro-op slot s of phase p.",
              "function automatic logic [8:0] sched(input logic [4:0] p, input logic [3:0] s);",
              "    sched = {U_END, 3'd0};",
              "    case ({p, s})"]
    longest = 0
    for p, text in enumerate(PHASES):
        slot = 0
        for step in text.split(";"):
            name, *voice = step.split()
            for u in EXPAND[name]:
                lines.append(f"        {{5'd{p}, 4'd{slot}}}: sched = {{U_{u}, 3'd{voice[0] if voice else 0}}};")
                slot += 1
        longest = max(longest, slot)
    lines += ["        default: ;", "    endcase", "endfunction",
              f"localparam int MAX_UOPS = {longest};", ""]
    assert longest < 16
    (ROOT / "src" / "sony_s_dsp_sched.svh").write_text("\n".join(lines))
    print(f"tables written; longest phase = {longest} micro-ops")


if __name__ == "__main__":
    main()

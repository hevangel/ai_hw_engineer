#!/usr/bin/env python3
"""Pin MAME's original VIC source and extract unchanged raster functions.

The original files and generated include remain ignored build artifacts.
The adapter does not recreate the raster equations in a self-written model.
"""
from pathlib import Path
import hashlib
import re
import urllib.request

ROOT = Path(__file__).resolve().parents[1] / "work/ntsc-reference"
REVISION = "41a494b6ef80adc924ccb2bdba1ee69580276e0c"
BASE = f"https://raw.githubusercontent.com/mamedev/mame/{REVISION}/src/devices/sound/"
FILES = {
    "mos6560.cpp": "d8b17b6c6bf47d2b52ddbab0ec5b7bb5c0ef1abe32a058964ed613c791aa198f",
    "mos6560.h": "36bd790c22f6f6f7f3d163bc5cbbec3d19f18289d322a0e5f67e028b302e89a9",
}
FUNCTIONS = (
    "device_reset", "raster_line", "last_line_cycles",
    "end_of_line", "end_of_frame", "cycle",
)
# The display adapter compiles the complete per-cycle state machine,
# register access, light-pen and sound functions, again byte-preserved.
DISPLAY_FUNCTIONS = (
    "device_reset", "raster_line", "last_line_cycles",
    "open_v", "close_v", "open_h", "handle_vmc", "count_vmc",
    "end_of_line", "end_of_frame", "fetch_byte", "fetch", "output_pixels",
    "trigger_light_pen", "cycle", "read", "write", "lp_w",
    "sound_stream_update",
)


def extract_function(source: str, name: str) -> str:
    """Select a complete, byte-preserved function from the pinned artifact."""
    pattern = rf"^(?:void|int|uint8_t) mos6560_device::{re.escape(name)}\([^\n]*\)(?: const)?\n\{{"
    matches = list(re.finditer(pattern, source, re.MULTILINE))
    if len(matches) != 1:
        raise SystemExit(f"Expected exactly one original function: {name}")
    match = matches[0]
    # These exact, hash-checked functions contain no brace characters inside
    # strings or comments. Count the original braces; never transform a body.
    depth = 1
    end = match.end()
    while end < len(source) and depth:
        if source[end] == "{":
            depth += 1
        elif source[end] == "}":
            depth -= 1
        end += 1
    if depth:
        raise SystemExit(f"Unbalanced original function: {name}")
    return source[match.start():end] + "\n"


def main() -> None:
    ROOT.mkdir(parents=True, exist_ok=True)
    for name, expected in FILES.items():
        path = ROOT / name
        if path.exists():
            data = path.read_bytes()
        else:
            with urllib.request.urlopen(BASE + name, timeout=60) as response:
                data = response.read()
        if hashlib.sha256(data).hexdigest() != expected:
            raise SystemExit(f"Original MAME source hash mismatch: {name}")
        if not path.exists():
            path.write_bytes(data)

    # Raw upstream uses LF. Reading bytes avoids Windows newline conversion.
    source = (ROOT / "mos6560.cpp").read_bytes().decode("utf-8")
    license_lines = "\n".join(source.splitlines()[:2]) + "\n"
    selected = [extract_function(source, name) for name in FUNCTIONS]
    header = (
        license_lines
        + f"// Exact function extraction from MAME {REVISION}.\n"
        + "// Generated by fetch_ntsc_reference.py; do not edit.\n\n"
    )
    (ROOT / "mame_raster_functions.inc").write_bytes(
        (header + "\n".join(selected)).encode("utf-8")
    )
    display = [extract_function(source, name) for name in DISPLAY_FUNCTIONS]
    # output_pixels uses this original file-scope constant; copy its line.
    delay = re.findall(r"^constexpr int OUTPUT_DELAY = \d+;\n", source, re.MULTILINE)
    if len(delay) != 1:
        raise SystemExit("Expected exactly one original OUTPUT_DELAY definition")
    (ROOT / "mame_display_functions.inc").write_bytes(
        (header + delay[0] + "\n" + "\n".join(display)).encode("utf-8")
    )
    print("Verified pinned original MAME VIC source/header; extracted six unchanged raster "
          f"functions and {len(display)} unchanged display/bus/sound functions")


if __name__ == "__main__":
    main()

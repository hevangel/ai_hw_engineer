#!/usr/bin/env python3
"""Compare the SCELBI 8B RTL against the console oracle over a full session.

Builds a Verilator testbench that dumps the RTL's architectural state at each
retirement and its console transcript, runs the same console session in the
oracle (work/scelbi_ref/oracle.py -> system/scelbi_8b/oracle/scelbi_oracle.py),
and diffs both.

Usage:
    python3 system/scelbi_8b/scripts/compare_oracle.py

Requires Verilator on PATH (the repository Docker image has it).
"""
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[3]
SYSTEM = ROOT / "system/scelbi_8b"
sys.path.insert(0, str(SYSTEM / "oracle"))
import scelbi_oracle as o  # noqa: E402

SESSION = (b'SCR\r10 A=1\r20 B=7\r30 PRINT "A + B =";\r40 PRINT A+B\r'
           b'50 END\rLIST\rRUN\r')
IDLE = 150153          # instructions the RTL retires during its idle window
LIMIT = 2_000_000

TB = r"""// Generated by scripts/compare_oracle.py: dump the RTL architectural state
// and console transcript for the oracle diff.
module tb_oracle;
    logic clk = 0;
    always #5 clk = ~clk;
    logic rst_n = 0;
    logic cpu_enable = 1;
    logic tty_rx_push = 0;
    logic [7:0] tty_rx_data = 0;
    logic tty_rx_full;
    logic [7:0] tty_tx_data;
    logic tty_tx_strobe;
    logic [13:0] host_mem_addr = 0;
    logic [7:0] host_mem_data = 0;
    logic host_mem_write = 0;
    logic [7:0] host_mem_read;
    logic [13:0] pc;
    logic [7:0] accumulator;
    logic [3:0] flags;
    logic halted, retired;
    logic [13:0] bus_addr;
    logic [7:0] bus_data;
    logic bus_mem_read, bus_write, bus_io_read, bus_io_write;
    logic [4:0] last_output_port;
    logic [7:0] last_output_data;
    logic [31:0] cycle_count, instruction_count;
    logic ptr_push = 0;
    logic [7:0] ptr_data = 0;
    logic ptr_empty;
    logic ptr_full;
    logic [7:0] ptr_byte;
    logic [31:0] ptr_read_count;

    scelbi_8b dut (.*);

    integer fpc, ftty, fd, k, slen = 0, code;
    logic [7:0] session [0:255];

    task automatic send_byte(input [7:0] value);
        begin
            @(negedge clk);
            while (tty_rx_full) @(negedge clk);
            tty_rx_data = value;
            tty_rx_push = 1;
            @(negedge clk);
            tty_rx_push = 0;
        end
    endtask

    initial begin
        for (k = 0; k < 256; k = k + 1) session[k] = 8'h00;
        fd = $fopen("work/tb_oracle/session.hex", "r");
        if (fd == 0) $fatal(1, "cannot open session file");
        while (!$feof(fd)) begin
            code = $fscanf(fd, "%h\n", session[slen]);
            if (code == 1) slen = slen + 1;
        end
        $fclose(fd);
        fpc = $fopen("work/tb_oracle/rtl_pc.txt", "w");
        ftty = $fopen("work/tb_oracle/rtl_tty.txt", "w");
        if (fpc == 0 || ftty == 0) $fatal(1, "cannot write RTL traces");
        repeat (2) @(negedge clk);
        rst_n = 1;
        repeat (300000) @(negedge clk);
        for (k = 0; k < slen; k = k + 1) send_byte(session[k]);
        repeat (4000000) @(negedge clk);
        $fclose(fpc);
        $fclose(ftty);
        $display("RTL retired %0d instructions, %0d console bytes",
                 instruction_count, dut.rx_rd);
        $finish;
    end

    always @(posedge clk) begin
        if (rst_n && retired && instruction_count < __LIMIT)
            $fdisplay(fpc, "%0d %0d %0d %0d %0d %0d %0d %0d %0d %0d",
                      dut.pc, dut.cpu.r[0], dut.cpu.r[1],
                      dut.cpu.r[2], dut.cpu.r[3], dut.cpu.r[4], dut.cpu.r[5],
                      dut.cpu.r[6],
                      {4'b0, dut.cpu.carry, dut.cpu.zero,
                       dut.cpu.sign, dut.cpu.parity},
                      dut.cpu.sp);
        if (rst_n && cpu_enable && tty_tx_strobe)
            $fwrite(ftty, "%c", tty_tx_data);
    end
endmodule
"""


def dec(b):
    return "".join(chr(c & 0x7F) if 32 <= (c & 0x7F) < 127 else "."
                   for c in b)


def oracle_state():
    """Return (rows, transcript) from the oracle over the same session."""
    o.reset()
    cpu = o.cpu
    rows = []
    n = 0
    # Idle window: the RTL idles for a fixed number of cycles before typing.
    while n < IDLE and not cpu.halted:
        cpu.step()
        rows.append((cpu.pc, cpu.a, cpu.b, cpu.c, cpu.d, cpu.e,
                     cpu.hl >> 8, cpu.hl & 0xFF,
                     (cpu.cf << 3) | (cpu.zf << 2) | (cpu.sf << 1) | cpu.pf,
                     cpu.sp))
        n += 1
    o.tty_in.extend(SESSION)
    quiet = 0
    while not cpu.halted and n < LIMIT:
        cpu.step()
        n += 1
        rows.append((cpu.pc, cpu.a, cpu.b, cpu.c, cpu.d, cpu.e,
                     cpu.hl >> 8, cpu.hl & 0xFF,
                     (cpu.cf << 3) | (cpu.zf << 2) | (cpu.sf << 1) | cpu.pf,
                     cpu.sp))
        if not o.tty_in:
            quiet += 1
            if quiet > 800_000:
                break
        else:
            quiet = 0
    return rows, bytes(b & 0x7F for b in o.tty_log)


def main():
    out = ROOT / "work/tb_oracle"
    out.mkdir(parents=True, exist_ok=True)
    (out / "session.hex").write_text("".join(f"{b:02x}\n" for b in SESSION))

    rows, ora_txt = oracle_state()
    print(f"oracle: {len(rows)} instructions, {len(ora_txt)} console bytes")

    tb = out / "tb_oracle.sv"
    tb.write_text(TB.replace("__LIMIT", str(LIMIT)))
    subprocess.run(
        ["verilator", "--binary", "--timing", "-Wno-fatal",
         "--top-module", "tb_oracle", "--Mdir", str(out / "obj"),
         str(ROOT / "design/intel_mcs8/intel_8008/src/intel_8008.sv"),
         str(SYSTEM / "src/scelbi_8b.sv"), str(tb)],
        check=True, cwd=ROOT, stdout=subprocess.DEVNULL)
    subprocess.run([str(out / "obj/Vtb_oracle"),
                    f"+image={SYSTEM}/build/scelbal.hex"],
                   check=True, cwd=ROOT)

    rtl = [tuple(int(x) for x in l.split())
           for l in (out / "rtl_pc.txt").read_text().split("\n") if l]
    rtl_txt = (out / "rtl_tty.txt").read_bytes()
    print(f"rtl: {len(rtl)} instructions, {len(rtl_txt)} console bytes")

    n = min(len(rtl), len(rows))
    bad = sum(1 for i in range(n) if rtl[i] != rows[i])
    if bad:
        first = next(i for i in range(n) if rtl[i] != rows[i])
        print(f"FAIL: {bad} of {n} instructions differ; first at {first}")
        for j in range(max(0, first - 3), min(n, first + 5)):
            print(f"   {j:8d} oracle {rows[j]}")
            print(f"   {j:8d} rtl    {rtl[j]}")
        return 1

    # Console transcript: the RTL keeps running after the oracle stops, so
    # compare the oracle's transcript as a prefix.
    rtl7 = bytes(b & 0x7F for b in rtl_txt)
    if rtl7.startswith(ora_txt):
        print(f"PASS: {n} instructions and {len(ora_txt)} console bytes "
              f"agree exactly (rtl continues past the oracle's stop)")
        return 0
    print(f"FAIL: console transcripts differ")
    print("  oracle:", dec(ora_txt))
    print("  rtl   :", dec(rtl7))
    return 1


if __name__ == "__main__":
    sys.exit(main())
#!/usr/bin/env python3
"""Generate a digital motherboard from physical connectivity, with explicit sockets.

Analog outputs and the CPU socket are ports until their models are verified.
No memory/address-decoder shortcuts are inserted into the board.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TIMING_FILE = ROOT / 'board/timing.json'


LEGACY_UNIFORM_NS = 5
# The 4116 carried a 20 ns placeholder in the original generated board.
LEGACY_OVERRIDES_NS = {'4116': 20}


def resolve_entry(parts, part):
    """Follow same_as aliases so both spellings of a device share one row."""
    seen = {part}
    entry = parts[part]
    while 'same_as' in entry:
        target = entry['same_as']
        if target in seen or target not in parts:
            raise SystemExit(f"timing.json: bad alias {part} -> {target}")
        seen.add(target)
        entry = parts[target]
    return entry


def load_timing(mode):
    """Return the per-part propagation delay for every modelled package.

    'legacy' and 'zero' reproduce the earlier placeholder boards. 'typ' and
    'max' take each package's delay from board/timing.json, and an entry that
    is not idealized must name the datasheet that publishes it: a
    characterized number without a source is a guess.

    Idealized packages (the DRAM and ROM models) keep their legacy value in
    every mode. Those models have no access-time behaviour, so a datasheet
    access delay would describe hardware the model does not contain.
    """
    table = json.loads(TIMING_FILE.read_text())
    parts = table['parts']
    if mode in ('legacy', 'zero'):
        uniform = 0 if mode == 'zero' else LEGACY_UNIFORM_NS
        overrides = LEGACY_OVERRIDES_NS if mode == 'legacy' else {}
        return {p: overrides.get(p, uniform) for p in parts}
    key = {'typ': 'typ_ns', 'max': 'max_ns'}[mode]
    delays = {}
    for part in parts:
        entry = resolve_entry(parts, part)
        if entry.get('idealized'):
            delays[part] = LEGACY_OVERRIDES_NS.get(part, LEGACY_UNIFORM_NS)
            continue
        if not entry.get('source'):
            raise SystemExit(f"timing.json: {part} has {key} but no datasheet source")
        value = entry.get(key)
        if not isinstance(value, int):
            raise SystemExit(f"timing.json: {part} has no integer {key} (mode {mode})")
        delays[part] = value
    return delays


def generate(timing_mode='legacy'):
    document = json.loads((ROOT/'board/rev0_connectivity.json').read_text())
    models = json.loads((ROOT/'board/models.json').read_text())
    delays = load_timing(timing_mode)
    components = document['components']
    all_nets = sorted({p['net'] for c in components.values() for p in c['pins'].values() if p['net']})
    # Electrical straps merge nets, rather than one-way assign connections.
    parent = {n:n for n in all_nets}
    def canonical(n):
        while parent[n] != n:
            n = parent[n]
        return n
    def join(a,b):
        a,b=canonical(a),canonical(b)
        parent[b]=a
    straps=[]
    for ref in ['D1','E1','F1']:
        for a,b in [('14','10'),('13','9'),('12','8')]:
            join(components[ref]['pins'][a]['net'],components[ref]['pins'][b]['net'])
            straps.append([ref,a,b])
    # A stable canonical symbol map keeps physical net labels in a sidecar.
    names={n:f'n{i:03d}' for i,n in enumerate(sorted({canonical(n) for n in all_nets}))}
    # Use the resolved top-level socket nets directly. This also avoids relying
    # on simulator support for tran primitives across module port boundaries.
    for i,p in enumerate(range(33,25,-1)):
        names[canonical(components['H7']['pins'][str(p)]['net'])]=f'cpu_data[{i}]'
    for bit in range(8):
        names[canonical(f'D{bit}')]=f'system_data_bus[{bit}]'
    def net(ref,pin):
        n=components[ref]['pins'][str(pin)]['net']
        return names[canonical(n)] if n else ''
    def named(n):return names[canonical(n)]
    lines=['// Generated by scripts/generate_rev0.py. Do not hand-edit.',
        '`timescale 1ns/1ps','`default_nettype none',
        'module apple_ii_rev0_digital #(',
        '    parameter bit RETAIN_DATA_BUS=1,',
        '    parameter ROM_D0="", ROM_D8="", ROM_E0="", ROM_E8="", ROM_F0="", ROM_F8="", CHAR_ROM=""',
        ') (',
        '    input logic master_oscillator, reset_n,',
        '    input logic [6:0] keyboard_data,',
        '    input logic keyboard_strobe,',
        '    input logic flash, cassette_in,',
        '    input logic [3:0] paddle_timer,',
        '    input logic [2:0] buttons,',
        '    input logic [15:0] cpu_address,',
        '    inout tri [7:0] cpu_data, system_data_bus,',
        '    input logic cpu_rw, cpu_phi1, cpu_phi2, cpu_sync,',
        '    output tri cpu_phi0, cpu_reset_n, cpu_irq_n, cpu_nmi_n, cpu_rdy,',
        '    output tri video_data, composite_sync, speaker, cassette_out, color_burst,',
        '    output tri [3:0] annunciators,',
        '    output tri paddle_trigger_n',
        ');']
    for n,symbol in names.items():
        if not symbol.startswith(('cpu_data[','system_data_bus[')):
            if n == 'GND':
                lines.append(f'    supply0 {symbol}; // Ideal ground; no rail impedance/current model.')
            elif n in ['+5V','+12V','-12V','-5V']:
                lines.append(f'    supply1 {symbol}; // Ideal power-good token, not analog voltage.')
            else:
                lines.append(f'    tri {symbol}; // {n}')
    # Ideal supplies dominate package outputs, including the real copper's
    # grounded unused H14 pin 6. Short-circuit current is outside this model.
    def assign_to(ref,pin,expression):lines.append(f'    assign {net(ref,pin)} = {expression};')
    assign_to('Q2',3,'master_oscillator')
    assign_to('B3',3,'flash')
    assign_to('H14',4,'cassette_in') # Boundary includes the series output resistor.
    for i,p in enumerate([1,8,9,16]):assign_to('H13',p,f'paddle_timer[{i}]')
    for i,p in enumerate([12,13,10,11,6,5,7]):assign_to('A7',p,f'keyboard_data[{i}]')
    assign_to('A7',2,'keyboard_strobe')
    # Reset is open collector, permitting the motherboard pull-up to release it.
    assign_to('A7',3,"reset_n ? 1'bz : 1'b0")
    for i,p in enumerate([2,3,4]):assign_to('J14',p,f'buttons[{i}]')
    for i,p in enumerate(list(range(9,21))+list(range(22,26))):assign_to('H7',p,f'cpu_address[{i}]')
    for p,signal in [(34,'cpu_rw'),(3,'cpu_phi1'),(39,'cpu_phi2'),(7,'cpu_sync')]:assign_to('H7',p,signal)
    for signal,p in [('cpu_phi0',37),('cpu_reset_n',40),('cpu_irq_n',4),('cpu_nmi_n',6),('cpu_rdy',2)]:
        lines.append(f'    assign {signal} = {net("H7",p)};')
    for signal,ref,p in [('color_burst','B12',12),('video_data','B10',5),('composite_sync','C13',8),('speaker','J13',5),('cassette_out','J13',8),('paddle_trigger_n','H13',3)]:
        # Validate all references exist; semantic signal taps are audited below.
        lines.append(f'    assign {signal} = {net(ref,p)};')
    for i,p in enumerate([15,14,13,12]):lines.append(f'    assign annunciators[{i}] = {net("J14",p)};')
    for ref in ['RA01','RA02']:
        c=components[ref]
        assert c['pins']['1']['net']=='+5V'
        for pin in list(c['pins'])[1:]:lines.append(f'    pullup pull_{ref}_{pin}({net(ref,pin)});')
    # Original unconnected TTL D input is electrically biased high. Explicit
    # approximation: unlike internal model X coercion this is visible/auditable.
    lines.append(f'    pullup floating_B10_D({net("B10",12)}); // ASSUMPTION: open TTL input reads high.')
    # ASSUMPTION: zero-delay charge with negligible half-cycle leakage;
    # Lancaster Enhancement 13 pp.196-198 documents the retained video byte.
    # A weak resolved value models passive charge, never an active bus driver.
    lines += ['    if (RETAIN_DATA_BUS) begin : charge_bus',
        '        // ASSUMPTION: ideal bus charge retention; spec/analog.md.',
        '        /* verilator lint_off PROCASSINIT */',
        '        /* verilator lint_off NOLATCH */ // Two-state lint cannot represent Z.',
        "        logic [7:0] held_charge = 8'bz;",
        '        for (genvar bit_number=0; bit_number<8; bit_number++) begin : bit_charge',
        "            always_latch if (system_data_bus[bit_number] !== 1'bz)",
        '                held_charge[bit_number] = system_data_bus[bit_number];',
        '        end',
        '        assign (weak1, weak0) system_data_bus = held_charge;',
        '        /* verilator lint_on NOLATCH */',
        '        /* verilator lint_on PROCASSINIT */',
        '    end']
    count=0
    for ref,c in components.items():
        if c['part'] not in models:continue
        model=models[c['part']]
        if c['part'] not in delays:raise SystemExit(f"timing.json: no delay for {c['part']} ({ref})")
        tpd=delays[c['part']]
        parameters=f' #(.T_PD({tpd}ns))'
        if c['part']=='ROM_Chip':parameters=f' #(.T_PD({tpd}ns), .ROM_FILE(ROM_{ref.split("-")[-1]}))'
        if c['part']=='2513':parameters=f' #(.T_PD({tpd}ns), .ROM_FILE(CHAR_ROM))'
        instance=ref.replace('-','_')
        if c['part']=='ROM_Chip':instance='socket_'+instance
        lines.append(f'    {model}{parameters} {instance} ('+', '.join(f'.p{p}({net(ref,p)})' for p in c['pins'])+');')
        count+=1
    lines+=['endmodule','`default_nettype wire','']
    metadata=dict(instantiated_packages=count,source=document['source'],straps=straps,
        net_symbols={n:names[canonical(n)] for n in all_nets},
        boundary_packages=['H7: CPU socket','B3: flash timer','H13: paddle timers','K13: cassette amplifier'],
        timing=dict(mode=timing_mode,units='ns',table='board/timing.json',
            part_delays={p:delays[p] for p in sorted({c['part'] for c in components.values() if c['part'] in models})}),
        status='Digital connectivity experiment; mixed-signal/full-board sign-off pending.')
    return '\n'.join(lines),json.dumps(metadata,indent=2)+'\n'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--timing',choices=['legacy','zero','typ','max'],default='legacy',
        help='per-part propagation delay set from board/timing.json')
    parser.add_argument('--out-src',help='write generated RTL here instead of src/')
    parser.add_argument('--out-json',help='write generated metadata here instead of board/')
    args=parser.parse_args()
    sv,metadata=generate(args.timing)
    outputs=[(Path(args.out_src) if args.out_src else ROOT/'src/apple_ii_rev0_digital.sv',sv),
             (Path(args.out_json) if args.out_json else ROOT/'board/rev0_generated.json',metadata)]
    for path,data in outputs:
        if args.check:
            if not path.exists() or path.read_text()!=data:raise SystemExit(f'Stale generated file: {path}')
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(data,encoding='utf-8',newline='\n')
    print('Generated wiring matches manifest.' if args.check
          else f'Revision-0 digital wiring generated from manifest ({args.timing} timing).')


if __name__=='__main__':main()
